/**
 * Chart of Accounts Model
 * الشجرة المحاسبية المتكاملة لنظام إدارة الفنادق
 * 
 * This file contains the complete chart of accounts structure
 * for a hotel/property management system following standard accounting principles.
 */

/**
 * Account Type Enum
 * أنواع الحسابات المحاسبية
 */
export enum AccountType {
  ASSET = 'asset',              // الأصول
  LIABILITY = 'liability',      // الخصوم
  EQUITY = 'equity',            // حقوق الملكية
  REVENUE = 'revenue',          // الإيرادات
  EXPENSE = 'expense'           // المصروفات
}

/**
 * Account Nature (Debit/Credit)
 * طبيعة الحساب (مدين/دائن)
 */
export enum AccountNature {
  DEBIT = 'debit',      // مدين (الأصول والمصروفات)
  CREDIT = 'credit'     // دائن (الخصوم وحقوق الملكية والإيرادات)
}

/**
 * Account Status
 * حالة الحساب
 */
export enum AccountStatus {
  ACTIVE = 'active',
  INACTIVE = 'inactive',
  ARCHIVED = 'archived'
}

/**
 * Account Interface
 * واجهة الحساب المحاسبي
 */
export interface Account {
  id: string;                          // رقم الحساب (مثل: 1010, 2010)
  code: string;                         // كود الحساب
  parentId?: string;                    // رقم الحساب الأب (للحسابات الفرعية)
  name: string;                         // اسم الحساب بالعربية
  nameEn: string;                       // اسم الحساب بالإنجليزية
  type: AccountType;                    // نوع الحساب
  nature: AccountNature;                // طبيعة الحساب
  level: number;                        // مستوى الحساب في الشجرة (1, 2, 3...)
  isParent: boolean;                    // هل الحساب أب (يحتوي على حسابات فرعية)
  isActive: boolean;                    // هل الحساب نشط
  status: AccountStatus;               // حالة الحساب
  description?: string;                 // وصف الحساب
  descriptionEn?: string;               // وصف الحساب بالإنجليزية
  notes?: string;                       // ملاحظات الحساب
  taxNumber?: string;                   // الرقم الضريبي
  balance: number;                      // الرصيد الحالي
  openingBalance: number;                // الرصيد الافتتاحي
  currency: string;                     // العملة (SAR, USD, etc.)
  isSystemAccount: boolean;            // هل الحساب نظامي (لا يمكن حذفه)
  allowManualEntry: boolean;           // هل يسمح بإدخال قيود يدوية
  displayOrder: number;                // ترتيب العرض
  tags?: string[];                     // علامات للحساب
  metadata?: Record<string, any>;       // بيانات إضافية
  createdAt?: Date;
  updatedAt?: Date;
  createdBy?: string;
  updatedBy?: string;
}

