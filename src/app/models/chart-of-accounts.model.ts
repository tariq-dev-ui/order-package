  static getAccountById(id: string): Account | undefined {
    return this.getAccounts().find(account => account.id === id);
  }

  /**
   * Get Account by Code
   * الحصول على حساب محدد بالكود
   */
  static getAccountByCode(code: string): Account | undefined {
    return this.getAccounts().find(account => account.code === code);
  }

  /**
   * Get Parent Accounts
   * الحصول على الحسابات الرئيسية فقط
   */
  static getParentAccounts(): Account[] {
    return this.getAccounts().filter(account => account.isParent && account.level <= 2);
  }

  /**
   * Get Child Accounts
   * الحصول على الحسابات الفرعية لحساب معين
   */
  static getChildAccounts(parentId: string): Account[] {
    return this.getAccounts().filter(account => account.parentId === parentId);
  }

  /**
   * Get Account Tree Structure
   * الحصول على هيكل الشجرة المحاسبية
   */
  static getAccountTree(): Account[] {
    const accounts = this.getAccounts();
    const tree: Account[] = [];
    const accountMap = new Map<string, Account & { children?: Account[] }>();

    // Create map of accounts
    accounts.forEach(account => {
      accountMap.set(account.id, { ...account, children: [] });
    });

    // Build tree structure
    accounts.forEach(account => {
      const accountWithChildren = accountMap.get(account.id)!;
      if (account.parentId) {
        const parent = accountMap.get(account.parentId);
        if (parent) {
          parent.children!.push(accountWithChildren);
        }
      } else {
        tree.push(accountWithChildren);
      }
    });

    return tree;
  }

  /**
   * Get Accounts for Dropdown/Select
   * الحصول على الحسابات للقوائم المنسدلة
   */
  static getAccountsForSelect(includeInactive: boolean = false): Array<{ value: string; label: string; labelEn: string }> {
    return this.getAccounts()
      .filter(account => includeInactive || account.isActive)
      .map(account => ({
        value: account.id,
        label: account.name,
        labelEn: account.nameEn
      }));
  }
